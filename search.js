/* Cozy Nest client-side search. Plain JS, no dependencies.
   Index (/search-index.json) is generated by build.py on every build:
   one entry per article — t = title, u = url, c = category,
   i = idea headings (in order; idea N links to #idea-N).
   Matching is token-based: every word of the query must appear in the
   same field. Rank: title match (0) > idea-heading match (1) > category
   match (2). Results show title + category (+ the matched idea heading
   when the match came from an idea). */
(function () {
  "use strict";
  var MAX_RESULTS = 12;
  var index = null;
  var indexPromise = null;

  function norm(s) { return (s || "").toLowerCase(); }
  function tokens(q) { return norm(q).trim().split(/\s+/).filter(Boolean); }
  function fieldHas(field, toks) {
    var f = norm(field);
    for (var k = 0; k < toks.length; k++) {
      if (f.indexOf(toks[k]) === -1) return false;
    }
    return toks.length > 0;
  }

  /* Pure ranking function — also exercised by the node test harness. */
  function rankResults(entries, query) {
    var toks = tokens(query);
    if (!toks.length) return [];
    var out = [];
    entries.forEach(function (e) {
      var best = -1;
      var ideaIdx = -1;
      if (fieldHas(e.t, toks)) {
        best = 0;
      } else {
        for (var j = 0; j < e.i.length; j++) {
          if (fieldHas(e.i[j], toks)) { best = 1; ideaIdx = j; break; }
        }
        if (best === -1 && fieldHas(e.c, toks)) best = 2;
      }
      if (best !== -1) out.push({ e: e, rank: best, idea: ideaIdx });
    });
    out.sort(function (a, b) { return a.rank - b.rank; });
    return out.slice(0, MAX_RESULTS);
  }

  function loadIndex() {
    if (!indexPromise) {
      indexPromise = fetch("/search-index.json")
        .then(function (r) { return r.json(); })
        .then(function (data) { index = data; return data; })
        .catch(function () { index = []; return []; });
    }
    return indexPromise;
  }

  function el(tag, cls, text) {
    var n = document.createElement(tag);
    if (cls) n.className = cls;
    if (text != null) n.textContent = text;
    return n;
  }

  function init() {
    var openBtn = document.getElementById("search-open");
    var overlay = document.getElementById("search-overlay");
    var input = document.getElementById("search-input");
    var closeBtn = document.getElementById("search-close");
    var hint = document.getElementById("search-hint");
    var results = document.getElementById("search-results");
    if (!openBtn || !overlay || !input || !results) return;
    var lastFocus = null;

    function render(query) {
      results.innerHTML = "";
      var q = query.trim();
      if (!q) { hint.hidden = false; return; }
      hint.hidden = true;
      if (!index) {
        results.appendChild(el("p", "search-empty", "Loading search…"));
        return;
      }
      var hits = rankResults(index, q);
      if (!hits.length) {
        results.appendChild(el("p", "search-empty", "No ideas found for “" + q + "”."));
        return;
      }
      hits.forEach(function (hit) {
        var a = el("a", "search-result");
        var url = hit.e.u;
        if (hit.rank === 1 && hit.idea >= 0) url += "#idea-" + (hit.idea + 1);
        a.href = url;
        a.appendChild(el("span", "search-result-title", hit.e.t));
        a.appendChild(el("span", "search-result-cat", hit.e.c));
        if (hit.rank === 1 && hit.idea >= 0) {
          a.appendChild(el("span", "search-result-idea", hit.e.i[hit.idea]));
        }
        results.appendChild(a);
      });
    }

    function open() {
      lastFocus = document.activeElement;
      overlay.hidden = false;
      document.body.style.overflow = "hidden";
      input.focus();
      loadIndex().then(function (data) {
        hint.textContent = "Search " + data.length + " lists — try “bathroom”, “bookshelf” or “fall”.";
        if (input.value.trim()) render(input.value);
      });
    }

    function close() {
      overlay.hidden = true;
      document.body.style.overflow = "";
      input.value = "";
      results.innerHTML = "";
      hint.hidden = false;
      if (lastFocus && lastFocus.focus) lastFocus.focus();
    }

    openBtn.addEventListener("click", open);
    closeBtn.addEventListener("click", close);
    overlay.addEventListener("click", function (ev) {
      if (ev.target === overlay) close();
    });
    document.addEventListener("keydown", function (ev) {
      if (ev.key === "Escape" && !overlay.hidden) close();
    });
    input.addEventListener("input", function () {
      if (index) { render(input.value); return; }
      loadIndex().then(function () { render(input.value); });
    });
  }

  if (typeof document !== "undefined") {
    if (document.readyState === "loading") {
      document.addEventListener("DOMContentLoaded", init);
    } else {
      init();
    }
  }

  /* Node test harness: require("./search.js").rankResults */
  if (typeof module !== "undefined" && module.exports) {
    module.exports = { rankResults: rankResults };
  }
})();
